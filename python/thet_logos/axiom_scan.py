def scan_one(blocks):
    d = irrep_dim(*blocks[0])
    Ds = [sample_D(blocks, i) for i in range(3)]
    ir_nuls = [irreducibility_nullity(d, D) for D in Ds]
    ir_pass = all(n == 1 for n in ir_nuls)
    # Orientability: 1 sample (provably universal-fail under the folded probe;
    # the single sample documents the residual).
    or_p, or_r = orientability(blocks, Ds[0])
    return dict(name=algebra_name(blocks), rdim=sum(real_dim(*b) for b in blocks), d=d,
                ir_nullities=ir_nuls, ir_pass=bool(ir_pass),
                or_pass=bool(or_p), or_residual=float(or_r))


def _worker(blocks):
    try:
        return scan_one(blocks), None
    except Exception as e:  # never let one algebra kill the scan
        return None, f"{algebra_name(blocks)}: {type(e).__name__}: {e}"


def main():
    t0 = time.time()
    cats = catalogue()
    print(f"catalogue: {len(cats)} algebras", flush=True)
    # warm caches in main process (also validates fb nullities vs corner rank)
    types = sorted({b[0] for b in cats})
    for (n, K) in types:
        fb = fb_data(n, K)
        _, rc, _ = ce_corner_rank([(n, K)])
        assert fb['nul'] == 272 - rc, (n, K, fb['nul'], rc)
    print(f"fb nullspaces ok ({len(types)} types)", flush=True)
    for d in sorted({irrep_dim(*t) for t in types}):
        st = ir_setup(d)
        exp = 2 + 2 * (8 - d) ** 2 + 128
        assert st['jg_nul'] == exp, (d, st['jg_nul'], exp)
    print("irreducibility J/Gamma reduction ok", flush=True)

    results, errors = [], []
    # Warm caches BEFORE forking so workers inherit them (fork on Linux).
    for (n, K) in types:
        fb_data(n, K)
    for d in sorted({irrep_dim(*t) for t in types}):
        ir_setup(d)
    print("caches warmed", flush=True)
    with Pool(NWORKERS) as pool:
        for i, (res, err) in enumerate(pool.imap_unordered(_worker, cats, chunksize=16)):
            if err:
                errors.append(err)
            else:
                results.append(res)
            if (i + 1) % 1000 == 0:
                print(f"  {i+1}/{len(cats)} ...", flush=True)
    print(f"errors: {len(errors)}", flush=True)
    for e in errors[:10]:
        print("  ERR", e)

    ir_pass_n = sum(1 for r in results if r['ir_pass'])
    or_pass_n = sum(1 for r in results if r['or_pass'])
    both_n = sum(1 for r in results if r['ir_pass'] and r['or_pass'])
    # split distribution for irreducibility
    from collections import Counter
    split = Counter(sum(1 for n in r['ir_nullities'] if n == 1) for r in results)
    af = [r for r in results if r['name'] == 'C+H+M_3(C)']
    out = dict(n_total=len(cats), n_ok=len(results),
               n_ir_pass=ir_pass_n, n_or_pass=or_pass_n, n_both=both_n,
               ir_split={str(k): v for k, v in sorted(split.items())},
               af=af[0] if af else None,
               results=results, errors=errors,
               wall_s=round(time.time() - t0, 1))
    with open('attack3_results.json', 'w') as f:
        json.dump(out, f)
    print(f"irreducibility all-3 pass: {ir_pass_n}/{len(results)}")
    print(f"orientability (1 sample) pass: {or_pass_n}/{len(results)}")
    print(f"both:                      {both_n}/{len(results)}")
    print(f"ir split (npass->count):    {dict(sorted(split.items()))}")
    print(f"A_F: {af[0] if af else None}")
    print(f"wall {time.time()-t0:.0f}s; wrote attack3_results.json")


def selftest():
    print("== fb nullspace vs corner rank ==")
    for (n, K) in [(1, 'R'), (1, 'C'), (1, 'H'), (2, 'R'), (2, 'C'),
                   (2, 'H'), (3, 'R'), (3, 'C'), (4, 'R'), (4, 'C'), (5, 'R')]:
        fb = fb_data(n, K)
        _, rc, _ = ce_corner_rank([(n, K)])
        print((n, K), "nul:", fb['nul'], "272-rank:", 272 - rc,
              "OK" if fb['nul'] == 272 - rc else "MISMATCH")
    print("== irreducibility reduction vs full system ==")
    for (n, K) in [(1, 'C'), (2, 'H')]:
        d = irrep_dim(n, K)
        D = sample_D([(n, K)], 0)
        n_red = irreducibility_nullity(d, D)
        gens = block_generators(n, K)
        Xm = []
        for Gg in gens:
            M = np.zeros((32, 32), complex); M[:d, :d] = Gg; Xm.append(M)
        Ym = [piOp(M) for M in Xm]
        n_full = commutant_nullity_real(Xm + Ym, D=D, use_J=True, use_Gamma=True)
        print((n, K), "reduced:", n_red, "full:", n_full,
              "OK" if n_red == n_full else "MISMATCH")
    print("== Poincare literal (A_F control) ==")
    AF = [(1, 'C'), (1, 'H'), (3, 'C')]
    Cap, ad = poincare_cap_literal(AF)
    print("Cap=\n", Cap, "\n|det| =", ad)
    print("== KO signs ==")
    print(ko_check(DF_ref()))


