def scan_algebra(blocks, enum_cap=ENUM_CAP):
    """Run the repaired battery on one algebra. Returns a result dict."""
    t0 = time.time()
    name = algebra_name(blocks)
    total = count_total_patterns(blocks)
    res = dict(name=name, blocks=[list(b) for b in blocks],
               total_patterns=total, n_tested=0,
               n_poincare_pass=0, n_orderone_pass=0,
               first_pass=None, first_faithful_pass=None,
               verdict=None, seconds=0.0)
    if total == 0:
        res['verdict'] = 'ruled_out_stage0'
        res['seconds'] = time.time() - t0
        return res
    for (m, S) in pattern_iter(blocks, cap=enum_cap):
        res['n_tested'] += 1
        faithful = pi_faithful(blocks, m, S)
        _, det = poincare_form(blocks, m, S)
        # Poincaré determinant NOT used as a filter (2026-09-26): KO-6
        # makes the 3-summand form singular by antisymmetry; see
        # poincare_form docstring. Recorded for diagnostics only.
        res['n_poincare_pass'] += 1
        pi_g, pio_g = build_reps(blocks, m, S)
        nul, Vnull, gap = order_one_nullspace(pi_g, pio_g)
        if nul < 1:
            continue
        res['n_orderone_pass'] += 1
        tag = f"{blocks}|{m}|{S}"
        ok = True
        diag = {}
        for sidx in range(N_D_SAMPLES):
            D = sample_D(Vnull, tag, sidx)
            ok_o, w = orientability_pass(pi_g, D)
            ir = irreducibility_nullity(pi_g, pio_g, D)
            if sidx == 0:
                diag = dict(orient_resid=float(w), irred_null=ir,
                            o1_nullity=nul, o1_gap=float(gap), det=float(det))
            if not ok_o or ir != 1:
                ok = False
                break
        if ok:
            rec = dict(m=list(m),
                       S=[list(n) if n is not None else None for n in S],
                       faithful=bool(faithful), **diag)
            if res['first_pass'] is None:
                res['first_pass'] = rec
            if faithful and res['first_faithful_pass'] is None:
                res['first_faithful_pass'] = rec
            if res['first_pass'] and res['first_faithful_pass']:
                break
    fp, ffp = res['first_pass'], res['first_faithful_pass']
    if fp is not None:
        res['verdict'] = ('faithfully_admissible' if ffp is not None
                          else 'admissible_unfaithful_only')
    elif total <= enum_cap and res['n_tested'] >= total:
        res['verdict'] = 'ruled_out'
    else:
        res['verdict'] = 'inconclusive_truncated'
    res['seconds'] = time.time() - t0
    return res


def _scan_one(args):
    blocks, cap = args
    try:
        return scan_algebra(blocks, enum_cap=cap)
    except Exception as e:  # never let one algebra kill the catalogue
        return dict(name=algebra_name(blocks),
                    blocks=[list(b) for b in blocks],
                    verdict='error', error=f"{type(e).__name__}: {e}")


def main(out_path=None, enum_cap=ENUM_CAP, workers=2):
    t0 = time.time()
    print("== Attack 4: repaired representation scan ==")
    print("Step 1: A_F control (stopping rule).")
    t1 = time.time()
    ctl = control_AF(verbose=True)
    print(f"  control wall time: {time.time()-t1:.1f}s")
    print("CONTROL PASSED. Running catalogue.")
    cats = catalogue()
    print(f"Step 2: Stage 0 + battery over {len(cats)} algebras "
          f"({workers} workers, cap {enum_cap}).")
    with Pool(workers) as pool:
        results = pool.map(_scan_one, [(b, enum_cap) for b in cats],
                           chunksize=8)
    # verdict tallies
    from collections import Counter
    tally = Counter(r['verdict'] for r in results)
    print("Verdict tally:", dict(tally))
    adm = [r for r in results if r['verdict'] in
           ('faithfully_admissible', 'admissible_unfaithful_only')]
    print(f"Admissible algebras: {len(adm)}")
    for r in adm:
        fp = r['first_pass']
        print(f"  {r['name']}: {r['verdict']} "
              f"(m={fp['m']}, faithful={fp['faithful']}, "
              f"det={fp['det']:.4f}, o1null={fp['o1_nullity']})")
    out = dict(control=ctl, tally=dict(tally), results=results,
               enum_cap=enum_cap,
               seconds=time.time() - t0)
    if out_path:
        with open(out_path, 'w') as f:
            json.dump(out, f)
        print(f"wrote {out_path}")
    return out


