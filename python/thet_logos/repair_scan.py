def poincare_form(blocks, m, S):
    """Intersection form C_{ij} = Tr(Gamma_F pi(p_i) pi^circ(p_j)) on K_0.

    Returns (C, det). Uses only the central projectors: orientation-free.

    KO-DIMENSION-6 OBSTRUCTION (documented 2026-09-26):
    Under the repository's KO-6 conventions (J^2=1, JD=DJ, JΓ=-ΓJ), the
    finite intersection form is antisymmetric. A 3x3 antisymmetric matrix
    is necessarily singular, so abs(det) > 1e-8 is UNSATISFIABLE for the
    three-summand algebra C⊕H⊕M_3(C). Per Krajewski (arXiv:0809.5137),
    KO-6 Poincaré duality requires the four-summand
    C⊕C⊕H⊕M_3(C); the physical representation identifies the two C
    summands. The determinant is therefore reported for diagnostics only
    and MUST NOT be used as a pass/fail filter for three summands.
    """
    Pp, Qp = central_projectors(blocks, m, S)
    G = gamma_F()
    G1, G2 = G[:HALF, :HALF], G[HALF:, HALF:]
    k = len(blocks)
    C = np.zeros((k, k))
    for i in range(k):
        for j in range(k):
            C[i, j] = (np.trace(G1 @ Pp[i] @ Qp[j].T)
                       + np.trace(G2 @ Qp[i] @ Pp[j].T)).real
    return C, float(abs(np.linalg.det(C)))


def order_one_nullspace(pi_gens, pio_gens):
    """Admissible D_F moduli: nullspace of D -> [[D,pi(a)],pi^circ(b)].

    Returns (nullity, V_null, gap): V_null is (272, nullity) real orthonormal;
    gap = smallest nonzero singular value / largest (diagnostic).
    """
    B = d_basis()
    R = None
    for X in pi_gens:
        BX = (np.einsum('kij,jl->kil', B, X)
              - np.einsum('ij,kjl->kil', X, B))
        for Y in pio_gens:
            V = (np.einsum('kij,jl->kil', BX, Y)
                 - np.einsum('ij,kjl->kil', Y, BX))
            F = np.concatenate([V.real.reshape(272, -1),
                                V.imag.reshape(272, -1)], axis=1).T
            R = F if R is None else np.linalg.qr(np.vstack([R, F]), mode='r')
    _, s, Vh = np.linalg.svd(R, compute_uv=True)
    smax = s[0]
    mask = s <= O1_TOL_REL * smax
    nullity = int(mask.sum())
    gap = float(s[nullity] / smax) if nullity < len(s) else float('inf')
    V_null = Vh[272 - nullity:].T.copy() if nullity else np.zeros((272, 0))
    return nullity, V_null, gap


def sample_D(V_null, tag, idx):
    """Deterministic generic D_F from the admissible nullspace."""
    nul = V_null.shape[1]
    h = hashlib.md5(f"{tag}|{idx}".encode()).hexdigest()
    seed = (SEED ^ int(h[:8], 16) ^ (idx * 0x9E3779B1)) & 0xFFFFFFFF
    rng = np.random.default_rng(seed)
    z = rng.standard_normal(nul)
    c = V_null @ z
    return np.tensordot(c, d_basis(), axes=([0], [0]))


def _commutant_basis(S_mats):
    """Complex-linear commutant basis of a list of 32x32 matrices.

    Returns (dim, Bmats): Bmats[j] is 32x32, orthonormal in Frobenius norm.
    """
    rows = []
    I = np.eye(DIM)
    for M in S_mats:
        rows.append(np.kron(M.T, I) - np.kron(I, M))
    F = np.vstack(rows)
    _, s, Vh = np.linalg.svd(F, compute_uv=True)
    dim = int((s <= TOL * s[0]).sum())
    Bmats = [Vh[1024 - dim + j].reshape(DIM, DIM) for j in range(dim)] if dim else []
    return dim, Bmats


def orientability_pass(pi_gens, D):
    """Gamma_F in the algebra generated by {pi_gens} U {[D, pi_g]}?

    Tests [Gamma_F, Y] = 0 for all Y in the commutant M' of that set,
    computed in the reduced space of commutant(pi_gens) for speed.
    Returns (ok, worst_residual).
    """
    G = gamma_F()
    # Stage 1: commutant of pi_gens
    r1, Bm = _commutant_basis(pi_gens)
    if r1 == 0:
        return False, float('inf')
    # Stage 2: impose [Y, [D, X]] = 0 for Y = sum c_j Bm_j
    W = [D @ X - X @ D for X in pi_gens]
    rows = []
    for Wk in W:
        for Bj in Bm:
            rows.append((Bj @ Wk - Wk @ Bj).reshape(-1))
    F = np.vstack(rows)  # (g*1024, r1) complex
    _, s, Vh = np.linalg.svd(F, compute_uv=True)
    dim = int((s <= TOL * s[0]).sum())
    if dim == 0:
        return False, float('inf')
    # null basis -> Y matrices; test [G, Y]
    worst = 0.0
    for j in range(dim):
        c = Vh[F.shape[1] - dim + j]
        Y = sum(c[jj] * Bm[jj] for jj in range(r1))
        nY = float(np.linalg.norm(Y))
        if nY < 1e-14:
            continue
        worst = max(worst, float(np.linalg.norm(G @ Y - Y @ G)) / nY)
    return worst < AX_TOL, worst


def irreducibility_nullity(pi_gens, pio_gens, D):
    """Real-linear nullity of the commutant of {pi, pi^circ, D, J, Gamma}.

    Staged: complex commutant of pi_gens first (dim r1), then the remaining
    real-linear constraints in that reduced space. Returns the nullity
    (should be 1 for irreducible).
    """
    G = gamma_F()
    r1, Bm = _commutant_basis(pi_gens)
    if r1 == 0:
        return 0
    # Unknowns c in C^r1, X = sum c_j B_j. Build complex-linear constraint
    # rows first, then realify.
    crows = []  # each row: complex vector length r1
    for Y in pio_gens:
        for Bj in Bm:
            crows.append((Bj @ Y - Y @ Bj).reshape(-1))
    for Bj in Bm:
        crows.append((Bj @ D - D @ Bj).reshape(-1))
    for Bj in Bm:
        crows.append((Bj @ G - G @ Bj).reshape(-1))
    # J-constraint: X U = U conj(X), real-linear; handle separately below.
    C = np.vstack(crows) if crows else np.zeros((0, r1), complex)
    # realify complex-linear rows: [Re w, -Im w; Im w, Re w]
    R1 = np.block([[C.real, -C.imag], [C.imag, C.real]])
    # J-constraint: X U = U conj(X), real-linear in x = [Re c; Im c].
    # XU - U conj(X) = sum_j (x_j A_j + y_j B_j) with
    #   A_j = B_j U - U conj(B_j),  B_j = i(B_j U + U conj(B_j)).
    U = U_SWAP
    JRfull = np.zeros((4096, 2 * r1))
    for j, Bj in enumerate(Bm):
        A = (Bj @ U - U @ Bj.conj()).reshape(-1)
        Bc = (1j * (Bj @ U + U @ Bj.conj())).reshape(-1)
        JRfull[:2048, j] = A.real
        JRfull[2048:, j] = A.imag
        JRfull[:2048, r1 + j] = Bc.real
        JRfull[2048:, r1 + j] = Bc.imag
    F = np.vstack([R1, JRfull])
    _, s, _ = np.linalg.svd(F, compute_uv=False)
    return int((s <= AX_TOL * s[0]).sum())


