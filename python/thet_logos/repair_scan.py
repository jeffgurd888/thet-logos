def count_solutions(ds, target):
    """Number of x in N^k with sum x_i ds_i == target (exact DP)."""
    dp = [0] * (target + 1)
    dp[0] = 1
    for d in ds:
        for s in range(d, target + 1):
            dp[s] += dp[s - d]
    return dp[target]


def gen_mults(ds, target, all_positive=False):
    """Lazily yield tuples x in N^k with sum x_i ds_i == target.

    Lexicographic order. If all_positive, every x_i >= 1.
    """
    k = len(ds)

    def rec(i, cur, used):
        if i == k:
            if used == target:
                yield tuple(cur)
            return
        d = ds[i]
        lo = 1 if all_positive else 0
        for mm in range(lo, (target - used) // d + 1):
            cur.append(mm)
            yield from rec(i + 1, cur, used + mm * d)
            cur.pop()

    yield from rec(0, [], 0)


def count_total_patterns(blocks):
    """Exact total number of (m, S) patterns (Stage 0 count, via DP)."""
    ds = [irrep_dim(*b) for b in blocks]
    total = 0
    for m in gen_mults(ds, HALF):
        c = 1
        for mi in m:
            if mi > 0:
                c *= count_solutions(ds, mi)
        total += c
    return total


def pattern_iter(blocks, cap=ENUM_CAP):
    """Lazily yield (m, S) patterns, at most cap, deterministic order.

    S is a tuple with S[i] = None (if m_i == 0) or a tuple n_{ij} with
    sum_j n_{ij} d_j == m_i. Phase 1 tries P-faithful m (all m_i >= 1)
    first; phase 2 covers the rest (deduped).
    """
    ds = [irrep_dim(*b) for b in blocks]
    k = len(blocks)
    seen = 0

    def gen_S(m, i, cur):
        # lazily yield S-tuples for fixed m; stops early via seen
        if seen >= cap:
            return
        if i == k:
            yield tuple(cur)
            return
        mi = m[i]
        if mi == 0:
            cur.append(None)
            yield from gen_S(m, i + 1, cur)
            cur.pop()
        else:
            for n in gen_mults(ds, mi):
                if seen >= cap:
                    return
                cur.append(n)
                yield from gen_S(m, i + 1, cur)
                cur.pop()

    for phase_positive in (True, False):
        for m in gen_mults(ds, HALF, all_positive=phase_positive):
            if not phase_positive and all(mi >= 1 for mi in m):
                continue  # already covered in phase 1
            for S in gen_S(m, 0, []):
                yield m, S
                seen += 1
                if seen >= cap:
                    return
            if seen >= cap:
                return


def pi_faithful(blocks, m, S):
    """Cheap faithfulness of pi = diag(P, Q) from (m, S) alone.

    Block j is killed by pi iff m_j == 0 (P kills it) AND no S_i sees it
    (n_{ij} == 0 for all i with m_i > 0).
    """
    k = len(blocks)
    for j in range(k):
        if m[j] >= 1:
            continue
        seen_by_Q = any(S[i] is not None and S[i][j] >= 1 for i in range(k))
        if not seen_by_Q:
            return False
    return True


