def build_reps(blocks, m, S):
    """Build generator matrices for the (m, S) representation.

    Returns (pi_gens, pio_gens): lists of 32x32 complex matrices, one per
    (block, generator); pio_gens[g] = piOp(pi_gens[g]).
    Canonical irrep orientations.
    """
    k = len(blocks)
    ds = [irrep_dim(*b) for b in blocks]
    gen_lists = [block_generators(*b) for b in blocks]
    poff, o = [], 0
    for i in range(k):
        poff.append(o)
        o += ds[i] * m[i]
    roff, o = [], 0
    for i in range(k):
        roff.append(o)
        o += ds[i] * m[i]
    assert poff and o == HALF or True
    pi_gens, pio_gens = [], []
    for b in range(k):
        for G in gen_lists[b]:
            P = np.zeros((HALF, HALF), complex)
            if m[b] > 0:
                o = poff[b]
                P[o:o + ds[b] * m[b], o:o + ds[b] * m[b]] = np.kron(G, np.eye(m[b]))
            R = np.zeros((HALF, HALF), complex)
            for l in range(k):
                ml = m[l]
                if ml == 0:
                    continue
                n = S[l]
                Sl = np.zeros((ml, ml), complex)
                so = 0
                for j in range(k):
                    djn = ds[j] * n[j]
                    if j == b and n[j] > 0:
                        Sl[so:so + djn, so:so + djn] = np.kron(G, np.eye(n[j]))
                    so += djn
                o = roff[l]
                R[o:o + ds[l] * ml, o:o + ds[l] * ml] = np.kron(np.eye(ds[l]), Sl)
            Q = R.conj()
            M = np.block([[P, np.zeros((HALF, HALF))],
                          [np.zeros((HALF, HALF)), Q]])
            pi_gens.append(M)
            pio_gens.append(piOp(M))
    return pi_gens, pio_gens


def central_projectors(blocks, m, S):
    """P(p_i), Q(p_i): 16x16 projectors for the minimal central projections."""
    k = len(blocks)
    ds = [irrep_dim(*b) for b in blocks]
    Pp = []
    o = 0
    for i in range(k):
        Ppi = np.zeros((HALF, HALF), complex)
        if m[i] > 0:
            Ppi[o:o + ds[i] * m[i], o:o + ds[i] * m[i]] = np.eye(ds[i] * m[i])
        Pp.append(Ppi)
        o += ds[i] * m[i]
    Rp = []
    for i in range(k):
        Rpi = np.zeros((HALF, HALF), complex)
        lo = 0
        for l in range(k):
            ml = m[l]
            if ml > 0:
                n = S[l]
                Sl = np.zeros((ml, ml), complex)
                so = 0
                for j in range(k):
                    djn = ds[j] * n[j]
                    if j == i and n[j] > 0:
                        Sl[so:so + djn, so:so + djn] = np.eye(djn)
                    so += djn
                Rpi[lo:lo + ds[l] * ml, lo:lo + ds[l] * ml] = np.kron(np.eye(ds[l]), Sl)
            lo += ds[l] * ml
        Rp.append(Rpi)
    Qp = [R.conj() for R in Rp]
    return Pp, Qp


def order_zero_residual(pi_gens, pio_gens):
    """max ||[pi(a), pi^circ(b)]||_F over generator pairs (should be ~0)."""
    worst = 0.0
    for X in pi_gens:
        for Y in pio_gens:
            worst = max(worst, float(np.linalg.norm(X @ Y - Y @ X)))
    return worst


def unitality_residual(blocks, m, S):
    """||sum_i pi(p_i) - I_32||_F (should be ~0 when sum m_i d_i == 16)."""
    Pp, Qp = central_projectors(blocks, m, S)
    P1 = sum(Pp)
    Q1 = sum(Qp)
    M = np.block([[P1, np.zeros((HALF, HALF))],
                  [np.zeros((HALF, HALF)), Q1]])
    return float(np.linalg.norm(M - np.eye(2 * HALF)))


