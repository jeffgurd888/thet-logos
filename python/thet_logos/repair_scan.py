def control_AF(verbose=True):
    """Run the full battery on the repaired A_F control triple.

    Returns a dict with all diagnostics. Raises AssertionError if any
    control fails (stopping rule: do not run the catalogue).
    """
    t0 = time.time()
    blocks, m, S = AF_BLOCKS, AF_M, AF_S
    assert pi_faithful(blocks, m, S), "control pi not faithful"
    assert unitality_residual(blocks, m, S) < TOL
    pi_g, pio_g = build_reps(blocks, m, S)
    oz = order_zero_residual(pi_g, pio_g)
    C, det = poincare_form(blocks, m, S)
    nul, Vnull, gap = order_one_nullspace(pi_g, pio_g)
    tag = f"{blocks}|{m}|{S}"
    ores, ires = [], []
    for sidx in range(N_D_SAMPLES):
        D = sample_D(Vnull, tag, sidx)
        ok_o, w = orientability_pass(pi_g, D)
        ores.append((ok_o, w))
        ires.append(irreducibility_nullity(pi_g, pio_g, D))
    out = dict(
        order_zero_residual=oz,
        poincare_matrix=np.round(C, 6).tolist(),
        poincare_det=det,
        order_one_nullity=nul,
        order_one_gap=gap,
        orientability=[(bool(o), float(w)) for o, w in ores],
        irreducibility_nullities=ires,
        faithful=True,
        seconds=time.time() - t0,
    )
    if verbose:
        print("A_F control:")
        print(f"  order-zero residual : {oz:.2e}")
        print(f"  Poincare det        : {det:.6f}")
        print(f"  Poincare matrix     :\n{np.round(C, 4)}")
        print(f"  order-one nullity   : {nul} (gap {gap:.2e})")
        print(f"  orientability       : {ores}")
        print(f"  irreducibility      : {ires}")
        print(f"  time                : {out['seconds']:.1f}s")
    assert oz < TOL, "control FAILED: order-zero"
    # Poincaré determinant filter DISABLED (2026-09-26): under KO-6 the
    # 3x3 intersection form is antisymmetric hence singular; see
    # poincare_form docstring. Nondegeneracy needs C⊕C⊕H⊕M_3(C).
    assert nul >= 1, "control FAILED: order-one (no admissible D_F)"
    assert all(o for o, _ in ores), "control FAILED: orientability"
    assert all(r == 1 for r in ires), "control FAILED: irreducibility"
    return out


